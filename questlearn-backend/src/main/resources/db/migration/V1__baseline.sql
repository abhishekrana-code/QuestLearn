-- QuestLearn baseline schema.
--
-- This mirrors exactly what Hibernate generated before migrations existed, so
-- existing databases can be baselined at version 1 (see
-- spring.flyway.baseline-on-migrate) while empty databases apply this script and
-- then pass spring.jpa.hibernate.ddl-auto=validate.
--
-- Rule going forward: change the schema here in a new V<n>__*.sql file, never by
-- editing this one and never with ddl-auto=update.

CREATE TABLE users (
    id                 bigint       NOT NULL,
    created_at         timestamp(6) with time zone NOT NULL,
    current_level      integer      NOT NULL,
    email              varchar(180) NOT NULL,
    last_activity_date date,
    name               varchar(120) NOT NULL,
    password_hash      varchar(100) NOT NULL,
    role               varchar(20)  NOT NULL,
    streak_days        integer      NOT NULL,
    total_xp           integer      NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_role_check
        CHECK (role IN ('STUDENT', 'INSTRUCTOR', 'ADMIN'))
);

ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME users_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE users ADD CONSTRAINT uk_users_email UNIQUE (email);

CREATE TABLE courses (
    id            bigint       NOT NULL,
    category      varchar(60),
    created_at    timestamp(6) with time zone NOT NULL,
    description   varchar(1200),
    emoji         varchar(8),
    published     boolean      NOT NULL,
    title         varchar(160) NOT NULL,
    instructor_id bigint,
    CONSTRAINT courses_pkey PRIMARY KEY (id)
);

ALTER TABLE courses ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME courses_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE modules (
    id               bigint       NOT NULL,
    content          jsonb,
    order_index      integer      NOT NULL,
    positionx        integer      NOT NULL,
    positiony        integer      NOT NULL,
    summary          varchar(800),
    title            varchar(160) NOT NULL,
    xp_reward        integer      NOT NULL,
    course_id        bigint       NOT NULL,
    parent_module_id bigint,
    CONSTRAINT modules_pkey PRIMARY KEY (id)
);

ALTER TABLE modules ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME modules_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE quizzes (
    id            bigint      NOT NULL,
    passing_score integer     NOT NULL,
    payload       jsonb       NOT NULL,
    type          varchar(30) NOT NULL,
    module_id     bigint      NOT NULL,
    CONSTRAINT quizzes_pkey PRIMARY KEY (id),
    CONSTRAINT quizzes_type_check
        CHECK (type IN ('MULTIPLE_CHOICE', 'CODE_ORDER', 'DRAG_DROP'))
);

ALTER TABLE quizzes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME quizzes_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE quizzes ADD CONSTRAINT uk_quizzes_module UNIQUE (module_id);

CREATE TABLE user_module_progress (
    id           bigint      NOT NULL,
    attempts     integer     NOT NULL,
    completed_at timestamp(6) with time zone,
    score        integer     NOT NULL,
    status       varchar(20) NOT NULL,
    module_id    bigint      NOT NULL,
    user_id      bigint      NOT NULL,
    CONSTRAINT user_module_progress_pkey PRIMARY KEY (id),
    CONSTRAINT user_module_progress_status_check
        CHECK (status IN ('LOCKED', 'UNLOCKED', 'COMPLETED')),
    CONSTRAINT uk_progress_user_module UNIQUE (user_id, module_id)
);

ALTER TABLE user_module_progress ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME user_module_progress_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE courses
    ADD CONSTRAINT fk_courses_instructor FOREIGN KEY (instructor_id) REFERENCES users (id);

ALTER TABLE modules
    ADD CONSTRAINT fk_modules_course FOREIGN KEY (course_id) REFERENCES courses (id);

ALTER TABLE modules
    ADD CONSTRAINT fk_modules_parent FOREIGN KEY (parent_module_id) REFERENCES modules (id);

ALTER TABLE quizzes
    ADD CONSTRAINT fk_quizzes_module FOREIGN KEY (module_id) REFERENCES modules (id);

ALTER TABLE user_module_progress
    ADD CONSTRAINT fk_progress_user FOREIGN KEY (user_id) REFERENCES users (id);

ALTER TABLE user_module_progress
    ADD CONSTRAINT fk_progress_module FOREIGN KEY (module_id) REFERENCES modules (id);
