-- Class-level deadline overrides.
--
-- A node's `due_at` is the course-wide date. One class can need a different date:
-- 10B writes the test on Friday, 10C on Monday. An override row is that exception,
-- and it only applies to learners who are members of that class.
--
-- The node's own date is never copied into this table, so clearing an override
-- always falls back to the course date instead of leaving a stale duplicate.
-- A learner who belongs to two classes of one course gets the earliest override,
-- documented in EffectiveDeadlines: when two classes disagree, the stricter rule
-- wins, and the digest and the dashboard agree on it.

CREATE TABLE cohort_deadlines (
    id         bigint       NOT NULL,
    cohort_id  bigint       NOT NULL,
    module_id  bigint       NOT NULL,
    due_at     timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_cohort_deadlines PRIMARY KEY (id),
    CONSTRAINT fk_cohort_deadlines_cohort FOREIGN KEY (cohort_id) REFERENCES cohorts (id) ON DELETE CASCADE,
    CONSTRAINT fk_cohort_deadlines_module FOREIGN KEY (module_id) REFERENCES modules (id) ON DELETE CASCADE,
    CONSTRAINT uk_cohort_deadlines UNIQUE (cohort_id, module_id)
);

ALTER TABLE cohort_deadlines ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME cohort_deadlines_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_cohort_deadlines_module ON cohort_deadlines (module_id);
