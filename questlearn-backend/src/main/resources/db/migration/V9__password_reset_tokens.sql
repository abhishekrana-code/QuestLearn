-- Self-service password recovery.
--
-- Only a SHA-256 hash of each reset token is stored, so a database dump cannot be
-- replayed to take over accounts. Expiry is absolute (nothing depends on the app
-- clock being right at request time), and `used_at` makes a token single-use: the
-- confirming transaction claims the row with a conditional UPDATE, so two
-- simultaneous confirmations cannot both succeed.
--
-- Rows are deleted with their account and ignored once expired; they are never
-- reused, and issuing a new link marks every earlier unused link for that account
-- as used.

CREATE TABLE password_reset_tokens (
    id         bigint       NOT NULL,
    user_id    bigint       NOT NULL,
    token_hash varchar(64)  NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at    timestamp(6) with time zone,
    CONSTRAINT pk_password_reset_tokens PRIMARY KEY (id),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_password_reset_tokens_hash UNIQUE (token_hash)
);

ALTER TABLE password_reset_tokens ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME password_reset_tokens_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens (user_id);
