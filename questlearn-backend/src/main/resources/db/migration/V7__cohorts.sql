-- Cohorts: the class behind a course.
--
-- Enrollment answers "this learner joined this course". A cohort answers "and
-- they are in 10B", which is what a teacher needs to run a term, share a join
-- code and read a roster that is not the whole building.
--
-- Membership is deliberately separate from enrollment: a learner who leaves the
-- course shows up on the course roster as gone, but their cohort row keeps the
-- class list truthful. Leaving a cohort is not an access change either - the
-- catalogue is still open.

CREATE TABLE cohorts (
    id         bigint                      NOT NULL,
    course_id  bigint                      NOT NULL,
    name       varchar(120)                NOT NULL,
    join_code  varchar(12)                 NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT cohorts_pkey PRIMARY KEY (id),
    CONSTRAINT uk_cohorts_join_code UNIQUE (join_code),
    CONSTRAINT fk_cohorts_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE
);

ALTER TABLE cohorts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME cohorts_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_cohorts_course ON cohorts (course_id);

CREATE TABLE cohort_memberships (
    id        bigint                      NOT NULL,
    cohort_id bigint                      NOT NULL,
    user_id   bigint                      NOT NULL,
    joined_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT cohort_memberships_pkey PRIMARY KEY (id),
    CONSTRAINT uk_cohort_membership UNIQUE (cohort_id, user_id),
    CONSTRAINT fk_cohort_membership_cohort FOREIGN KEY (cohort_id) REFERENCES cohorts (id) ON DELETE CASCADE,
    CONSTRAINT fk_cohort_membership_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

ALTER TABLE cohort_memberships ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME cohort_memberships_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_cohort_memberships_cohort ON cohort_memberships (cohort_id);
CREATE INDEX idx_cohort_memberships_user ON cohort_memberships (user_id);
