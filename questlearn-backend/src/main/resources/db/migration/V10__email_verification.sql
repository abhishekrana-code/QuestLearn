-- Address verification.
--
-- Accounts that already exist keep working and are treated as verified: they were
-- created before mail existed, and flipping them to unverified would nag every
-- demo account without any way for the owner to fix it. New sign-ups start false.
--
-- Verification tokens follow the reset-token rules: only the SHA-256 hash is
-- stored, each token is single-use through a conditional claim, expiry is
-- absolute, and issuing a new link kills the earlier ones.

ALTER TABLE users ADD COLUMN email_verified boolean NOT NULL DEFAULT true;
ALTER TABLE users ALTER COLUMN email_verified SET DEFAULT false;

CREATE TABLE email_verification_tokens (
    id         bigint       NOT NULL,
    user_id    bigint       NOT NULL,
    token_hash varchar(64)  NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    used_at    timestamp(6) with time zone,
    CONSTRAINT pk_email_verification_tokens PRIMARY KEY (id),
    CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_email_verification_tokens_hash UNIQUE (token_hash)
);

ALTER TABLE email_verification_tokens ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME email_verification_tokens_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_email_verification_tokens_user ON email_verification_tokens (user_id);
