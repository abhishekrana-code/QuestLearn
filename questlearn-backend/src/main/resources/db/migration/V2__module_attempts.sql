-- Every graded attempt at a node, so a student can see how their scores moved
-- across retries instead of only the single best score kept in
-- user_module_progress. Rows are deliberately small: score, whether it passed,
-- which route graded it and when.

CREATE TABLE module_attempts (
    id         bigint      NOT NULL,
    module_id  bigint      NOT NULL,
    user_id    bigint      NOT NULL,
    score      integer     NOT NULL,
    passed     boolean     NOT NULL,
    source     varchar(20) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT module_attempts_pkey PRIMARY KEY (id),
    CONSTRAINT module_attempts_source_check
        CHECK (source IN ('VIVA_SPOKEN', 'VIVA_WRITTEN', 'QUIZ')),
    CONSTRAINT module_attempts_score_check
        CHECK (score >= 0 AND score <= 100)
);

ALTER TABLE module_attempts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME module_attempts_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

ALTER TABLE module_attempts
    ADD CONSTRAINT fk_attempt_user FOREIGN KEY (user_id) REFERENCES users (id);

ALTER TABLE module_attempts
    ADD CONSTRAINT fk_attempt_module FOREIGN KEY (module_id) REFERENCES modules (id);

-- The node briefing reads the newest attempts for one learner and one node.
CREATE INDEX idx_attempt_user_module_created
    ON module_attempts (user_id, module_id, created_at DESC);
