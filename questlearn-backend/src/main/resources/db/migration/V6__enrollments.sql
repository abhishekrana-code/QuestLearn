-- Enrollment: the record that a learner has joined a course.
--
-- The catalogue stays open to every signed-in student, so this table is not an
-- access-control list. It is what turns "every course in the building" into
-- "my courses": the dashboard, the catalogue badge and the teacher's roster
-- count all read from here.
--
-- No row is written for instructors or admins; they reach courses through
-- ownership, not enrollment.

CREATE TABLE enrollments (
    id          bigint                     NOT NULL,
    user_id     bigint                     NOT NULL,
    course_id   bigint                     NOT NULL,
    enrolled_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT enrollments_pkey PRIMARY KEY (id),
    CONSTRAINT uk_enrollments_user_course UNIQUE (user_id, course_id),
    CONSTRAINT fk_enrollments_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE
);

ALTER TABLE enrollments ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME enrollments_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

-- The roster query reads by course; the dashboard reads by learner.
CREATE INDEX idx_enrollments_course ON enrollments (course_id);
CREATE INDEX idx_enrollments_user ON enrollments (user_id);

-- Anyone who has already touched a node in a course is enrolled in it, so
-- existing learners keep the courses they were working on instead of starting
-- with an empty dashboard after the upgrade.
INSERT INTO enrollments (user_id, course_id, enrolled_at)
SELECT progress.user_id,
       modules.course_id,
       COALESCE(MIN(progress.completed_at), now())
FROM user_module_progress progress
         JOIN modules ON modules.id = progress.module_id
GROUP BY progress.user_id, modules.course_id;
