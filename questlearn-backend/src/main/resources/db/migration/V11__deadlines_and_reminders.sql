-- Deadlines and reminder digests.
--
-- A deadline belongs to one skill node and applies to the whole course. It is
-- deliberately soft: a learner can still open and complete the node after it,
-- and the product records that the completion was late instead of blocking the
-- work. A school that needs a hard cut-off can read the late flag from the
-- roster; a mail outage or a sick day never locks a class out.
--
-- `deadline_reminders` is the dedupe ledger for the daily digest. A reminder is
-- keyed by (learner, node, kind, due date) so:
--   * the same learner is not emailed twice about the same deadline,
--   * moving the deadline makes a fresh reminder legitimate,
--   * the due-soon and overdue messages are tracked separately.
--
-- `notify_deadlines` is the per-account opt-out. Defaults to true for existing
-- and new accounts; a learner can turn the digest off from the dashboard.

ALTER TABLE modules ADD COLUMN due_at timestamp(6) with time zone;

ALTER TABLE users ADD COLUMN notify_deadlines boolean NOT NULL DEFAULT true;

CREATE TABLE deadline_reminders (
    id         bigint       NOT NULL,
    user_id    bigint       NOT NULL,
    module_id  bigint       NOT NULL,
    kind       varchar(16)  NOT NULL,
    due_at     timestamp(6) with time zone NOT NULL,
    sent_at    timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_deadline_reminders PRIMARY KEY (id),
    CONSTRAINT fk_deadline_reminders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_deadline_reminders_module FOREIGN KEY (module_id) REFERENCES modules (id) ON DELETE CASCADE,
    CONSTRAINT uk_deadline_reminders UNIQUE (user_id, module_id, kind, due_at),
    CONSTRAINT deadline_reminders_kind_check CHECK (kind IN ('DUE_SOON', 'OVERDUE'))
);

ALTER TABLE deadline_reminders ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME deadline_reminders_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_deadline_reminders_sent_at ON deadline_reminders (sent_at);
