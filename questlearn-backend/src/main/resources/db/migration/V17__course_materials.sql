-- Course materials are PDFs processed by the separate VerityAI service.
--
-- QuestLearn owns the course and the permission check; VerityAI owns the file,
-- the extracted text and the page-level citations. The row here is the bridge:
-- it records which VerityAI document belongs to which course, so a question is
-- always asked against that course's materials and nothing else.
--
-- Deleting a course removes its rows. Deleting an account keeps the material:
-- the class still needs the reading, so the uploader reference is cleared.

CREATE TABLE course_materials (
    id                  bigint                      NOT NULL,
    course_id           bigint                      NOT NULL,
    verity_document_id  uuid                        NOT NULL,
    uploaded_by         bigint,
    filename            varchar(255)                NOT NULL,
    size_bytes          bigint                      NOT NULL DEFAULT 0,
    status              varchar(20)                 NOT NULL,
    error_message       varchar(500),
    created_at          timestamp(6) with time zone NOT NULL,
    updated_at          timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_course_materials PRIMARY KEY (id),
    CONSTRAINT uk_course_materials_verity_document UNIQUE (verity_document_id),
    CONSTRAINT fk_course_materials_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_materials_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id) ON DELETE SET NULL
);

ALTER TABLE course_materials ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME course_materials_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_course_materials_course ON course_materials (course_id, created_at DESC);
