-- Who has read which note.
--
-- Read state belongs to the reader, not to the note: the same announcement is
-- unread for one learner and read for another, so it cannot live on the
-- announcements row. A row exists only once the learner has read the note, which
-- keeps "not read yet" the default for every note ever posted.
--
-- Both references cascade: removing a note or an account leaves nothing to mark.
-- The pair is unique, so opening the same note twice cannot count twice.

CREATE TABLE announcement_reads (
    id              bigint                      NOT NULL,
    announcement_id bigint                      NOT NULL,
    user_id         bigint                      NOT NULL,
    read_at         timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_announcement_reads PRIMARY KEY (id),
    CONSTRAINT uk_announcement_read UNIQUE (announcement_id, user_id),
    CONSTRAINT fk_announcement_read_announcement FOREIGN KEY (announcement_id) REFERENCES announcements (id) ON DELETE CASCADE,
    CONSTRAINT fk_announcement_read_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

ALTER TABLE announcement_reads ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME announcement_reads_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_announcement_reads_user ON announcement_reads (user_id);
