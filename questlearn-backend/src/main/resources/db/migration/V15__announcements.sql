-- Course announcements: a teacher's note to a class.
--
-- An announcement belongs to one course and, optionally, to one class inside it.
-- The class column is what keeps "10B writes the test on Friday" off 10C's
-- dashboard. It cascades with the class, so tidying up a term cannot leave a note
-- addressed to a class that no longer exists.
--
-- Deleting the author must not delete the note the class already read, so the
-- author reference is set to null instead. A course announcement goes with its
-- course: there is nothing left to read it against.

CREATE TABLE announcements (
    id         bigint        NOT NULL,
    course_id  bigint        NOT NULL,
    cohort_id  bigint,
    author_id  bigint,
    body       varchar(2000) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT pk_announcements PRIMARY KEY (id),
    CONSTRAINT fk_announcements_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_announcements_cohort FOREIGN KEY (cohort_id) REFERENCES cohorts (id) ON DELETE CASCADE,
    CONSTRAINT fk_announcements_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL
);

ALTER TABLE announcements ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME announcements_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE INDEX idx_announcements_course ON announcements (course_id, created_at DESC);
CREATE INDEX idx_announcements_cohort ON announcements (cohort_id);
