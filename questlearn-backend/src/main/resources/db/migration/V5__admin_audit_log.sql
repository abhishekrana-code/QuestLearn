-- Append-only record of privileged actions.
--
-- Schools ask "who promoted this account to admin?" and "who reset that
-- password?". Without this table there is no answer. Rows are written in the
-- same transaction as the action they describe, so a rolled-back action never
-- leaves a phantom entry and a committed action is never missing one.

CREATE TABLE admin_audit_log (
    id          bigint       NOT NULL,
    actor_id    bigint,
    actor_email varchar(180) NOT NULL,
    action      varchar(60)  NOT NULL,
    target      varchar(200) NOT NULL,
    detail      varchar(400),
    created_at  timestamp(6) with time zone NOT NULL,
    CONSTRAINT admin_audit_log_pkey PRIMARY KEY (id)
);

ALTER TABLE admin_audit_log ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME admin_audit_log_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

-- The admin page reads the newest rows first.
CREATE INDEX idx_admin_audit_created_at ON admin_audit_log (created_at DESC);

-- Keep the entry if the actor's account is later deleted; the email is the record.
ALTER TABLE admin_audit_log
    ADD CONSTRAINT fk_admin_audit_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL;
